"""Build the VR menu's translation class from its table.

tools/vr-text-ru.txt holds the in-game VR text in Russian: one "English => Russian"
pair per line, # for comments. The English side is the text the script draws, or
a template whose * parts stand for any text ("PAGE * OF *"); the Russian side has
the same number of *, in the order they are filled. VRText.uc explains the lookup.

The script package's source stays ASCII: every other character in a translation is
written as "~" and one character of the class's Alphabet, which its Codes decode.

    python tools/vr_text.py           write script/KF2VR/Classes/VRTextRussian.uc
    python tools/vr_text.py --check   exit 1 when that file is not up to date
"""
import string
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TABLE = ROOT / "tools/vr-text-ru.txt"
SEPARATOR = " => "
CLASS = ROOT / "script/KF2VR/Classes/VRTextRussian.uc"
# Characters that can follow "~": printable ASCII but the quote, backslash, tilde and space.
ALPHABET = "".join(c for c in string.printable[:94] if c not in '"\\~')
UNSAFE = set('"\\~')


def read(path=TABLE):
    """The table's (English, Russian) pairs, in file order."""
    pairs, seen = [], {}
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if line.count(SEPARATOR) != 1:
            raise ValueError(f"{path.name}:{number}: expected English => Russian")
        english, shown = line.split(SEPARATOR)
        if english != english.strip() or shown != shown.strip() or not english or not shown:
            raise ValueError(f"{path.name}:{number}: no empty sides or outer spaces")
        if english in seen:
            raise ValueError(f"{path.name}:{number}: {english!r} is already on line {seen[english]}")
        if english.count("*") != shown.count("*") or "**" in english:
            raise ValueError(f"{path.name}:{number}: the * parts differ or touch")
        if any(ord(c) > 126 or c in UNSAFE for c in english):
            raise ValueError(f"{path.name}:{number}: the English side must be plain ASCII without \" \\ ~")
        seen[english] = number
        pairs.append((english, shown))
    return pairs


def codes(pairs):
    """Every character a translation needs escaped, in a stable order."""
    needed = sorted({c for _, shown in pairs for c in shown if ord(c) > 126 or c in UNSAFE})
    if len(needed) > len(ALPHABET):
        raise ValueError(f"{len(needed)} characters to escape; the alphabet holds {len(ALPHABET)}")
    return needed


def encode(text, needed):
    return "".join("~" + ALPHABET[needed.index(c)] if c in needed else c for c in text)


def decode(text, alphabet, numbers):
    out, i = [], 0
    while i < len(text):
        if text[i] == "~" and i + 1 < len(text):
            i += 1
            index = alphabet.find(text[i])
            out.append(chr(numbers[index]) if 0 <= index < len(numbers) else text[i])
        else:
            out.append(text[i])
        i += 1
    return "".join(out)


def ordered(pairs):
    """Whole texts first; then templates, the one with the most fixed text first, which
    VRText tries in order ("BACK *cm" before "BACK *")."""
    exact = [pair for pair in pairs if "*" not in pair[0]]
    templates = [pair for pair in pairs if "*" in pair[0]]
    return exact + sorted(templates, key=lambda pair: -len(pair[0].replace("*", "")))


def source(pairs):
    pairs = ordered(pairs)
    needed = codes(pairs)
    lines = ["// Generated by tools/vr_text.py from tools/vr-text-ru.txt. Edit the table, not this file.",
             "// The Russian VR text for VRText; \"~\" and one Alphabet character stand for Codes' character.",
             "class VRTextRussian extends Object;", "",
             "var array<string> En, Ru;", "var string Alphabet;", "var array<int> Codes;", "",
             "defaultproperties", "{",
             f'    Alphabet="{ALPHABET[:len(needed)]}"']
    lines += [f"    Codes({i})={ord(c)}" for i, c in enumerate(needed)]
    for i, (english, shown) in enumerate(pairs):
        lines.append(f'    En({i})="{english}"')
        lines.append(f'    Ru({i})="{encode(shown, needed)}"')
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv):
    text = source(read())
    current = CLASS.read_text(encoding="ascii").replace("\r\n", "\n") if CLASS.exists() else ""
    if "--check" in argv:
        if current != text:
            print(f"{CLASS.relative_to(ROOT)} is out of date; run python tools/vr_text.py")
            return 1
        return 0
    if current != text:
        CLASS.write_text(text, encoding="ascii", newline="\n")
        print(f"wrote {CLASS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

"""Generate world toss/catch cues from shipped KF2 weapon AnimSet imports.

Only pure handling events qualify: put-away, pull-out, rustle, rattle or equip.
An equip clip's reload, chamber, sight and gun-check sounds never qualify.
Read original sound-bank exports too: many handling cues are absent from
animation imports. Shared pistol/rifle rattles are the last fallback.
Reads installed SDK metadata and cooked assets; never launches the game/editor.

    python tools/world_handling_sounds.py --write
"""
from __future__ import annotations

import argparse
from pathlib import Path
import re
from functools import cache

import reload_sound_map as assets

ROOT = Path(__file__).resolve().parents[1]
PURE = re.compile(r'_(PullOut|PutAway|Rustle|Rattle|Equip|Unequip)$', re.I)
SHARED_RIFLE = 'WW_WEP_Shared.Play_Rifle_Rattle'
SHARED_PISTOL = 'WW_WEP_Shared.Play_Pistol_Rattle'


def supported():
    rows = {}
    for line in (ROOT / 'script/KF2VR/Classes/VRHandsBridge.uc').read_text(encoding='utf-8').splitlines():
        match = re.search(r'WeaponProfiles\(\d+\)=\(WeaponClassName=(\w+),', line)
        if match and 'bFirearm=true' in line:
            rows[match[1]] = 'bOneHanded=true' in line
    return rows


def choose(events, caught, impact=False):
    if impact:
        events = [event for event in events if PURE.search(event)[1].lower() in ('rustle', 'rattle')]
        return min(events) if events else ''
    priorities = ('pullout', 'equip', 'rustle', 'rattle', 'putaway', 'unequip') if caught else (
        'putaway', 'unequip', 'rustle', 'rattle', 'pullout', 'equip')
    return min(events, key=lambda event: (priorities.index(PURE.search(event)[1].lower()), event))


@cache
def own_banks(weapon):
    """Resolve authored firing-bank references rather than guessing names."""
    while weapon:
        source = assets.class_text(weapon)
        # A borrowed dry-fire click does not identify this gun's own bank.
        lines = [line for line in source.splitlines() if re.search(r'WeaponFireSnd\(', line)]
        banks = {bank for line in lines for bank in re.findall(r"AkEvent'([^'.]+)\.", line, re.I)}
        if banks:
            return banks
        parent = re.search(r'\bclass\s+\w+\s+extends\s+(\w+)', source)
        weapon = parent[1] if parent else None
    return set()


@cache
def bank_events(path):
    source = assets.Package(path)
    return {path.stem + '.' + obj['name'] for obj in source.objects
            if obj['cls'] == 'AkEvent' and PURE.search(obj['name'])}


def collect():
    packages = {path.name.lower(): path for path in assets.WEAPONS.rglob('*.upk')}
    audio = {path.stem.lower(): path for path in (assets.GAME / 'KFGame/BrewedPC/Packages/Audio/SFX').glob('*.upk')}
    rows = []
    for weapon, one_handed in sorted(supported().items()):
        animset = assets.class_value(weapon, r'FirstPersonAnimSetNames\(0\)')
        package = packages.get(animset.split('.')[0].lower() + '.upk') if animset else None
        events = []
        if package:
            source = assets.Package(package)
            events = sorted({source.import_path(-i - 1) for i, obj in enumerate(source.imports)
                             if obj['cls'] == 'AkEvent' and PURE.search(obj['name'])})
        originals = set()
        for bank in own_banks(weapon):
            if bank.lower() != 'ww_wep_shared' and bank.lower() in audio:
                originals.update(bank_events(audio[bank.lower()]))
        choices = sorted(originals) or events
        fallback = SHARED_PISTOL if one_handed else SHARED_RIFLE
        rows.append((weapon, choose(choices, False) if choices else fallback,
                     choose(choices, True) if choices else fallback,
                     choose(sorted(originals), False, True) or choose(events, False, True) or fallback,
                     not originals and (not events or all('WW_WEP_Shared.' in event for event in events))))
    return rows


def generate(rows):
    lines = ['// GENERATED by tools/world_handling_sounds.py --write from shipped weapon',
             '// original sound banks and AnimSets. Pure handling; shared rattle as fallback.',
             "class VRWorldHandlingSounds extends Object;", '', 'struct HandlingCue', '{',
             '    var name Weapon;', '    var string ReleaseSound, CatchSound, ImpactSound;', '};',
             'var array<HandlingCue> Cues;', '',
             'static function string Find(name Weapon, bool bCaught, optional bool bImpact)', '{', '    local int I;',
             '    for (I = 0; I < default.Cues.Length; ++I)',
             '        if (default.Cues[I].Weapon == Weapon)',
             '            return bImpact ? default.Cues[I].ImpactSound : (bCaught ? default.Cues[I].CatchSound : default.Cues[I].ReleaseSound);',
             '    return "";', '}', '',
             'static function string EventPath(class<KFWeapon> WeaponClass, bool bCaught, optional bool bImpact)', '{',
             '    local int I;', '    local string Path;', '    local name Weapon;',
             '    if (WeaponClass == None) return "";',
             "    WeaponClass = class'VRWeaponDropState'.static.FamilyFor(WeaponClass);",
             '    Weapon = WeaponClass.Name;', '    Path = Find(Weapon, bCaught, bImpact);',
             '    if (Path != "") return Path;',
             "    for (I = 0; I < class'VRHandsBridge'.default.AuditedSubclasses.Length; ++I)",
             "        if (class'VRHandsBridge'.default.AuditedSubclasses[I].SubclassName == Weapon)",
             "            return Find(class'VRHandsBridge'.default.AuditedSubclasses[I].ProfileClassName, bCaught, bImpact);",
             '    return "";', '}', '', 'defaultproperties', '{']
    for i, (weapon, release, catch, impact, _) in enumerate(rows):
        lines.append(f'    Cues({i})=(Weapon={weapon},ReleaseSound="{release}",CatchSound="{catch}",ImpactSound="{impact}")')
    return '\n'.join(lines + ['}', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='Write VRWorldHandlingSounds.uc')
    args = parser.parse_args()
    rows = collect()
    if args.write:
        path = ROOT / 'script/KF2VR/Classes/VRWorldHandlingSounds.uc'
        path.write_text(generate(rows), encoding='utf-8', newline='\n')
        print(path)
    print(f'{len(rows)} firearm profiles; {sum(not row[4] for row in rows)} original handling sets; '
          f'{sum(row[4] for row in rows)} shared KF2 handling fallbacks')
    print('Shared fallback:', ', '.join(row[0] for row in rows if row[4]))


if __name__ == '__main__':
    main()

"""Turn KF2VR_ATTACKSIDE log lines (replay op `attacksides`, #210) into the
per-Zed attack table: which arm strikes at each melee impact of each clip.

    python tools/replay/attack_sides.py <game.log>... --json docs/re/zed-attack-sides.json --md docs/re/ZED_ATTACK_SIDES.md
"""
import argparse
import json
import re
import sys
from pathlib import Path

LINE = re.compile(r'KF2VR_ATTACKSIDE (?P<body>.*)$')
SIDES = {1: 'left', 2: 'right', 3: 'both'}


def parse(lines):
    rows = []
    for line in lines:
        m = LINE.search(line)
        if not m:
            continue
        fields = dict(part.split('=', 1) for part in m.group('body').split() if '=' in part)
        row = {
            'zed': fields.get('zed', ''),
            'tag': fields.get('tag', ''),
            'clip': fields.get('clip', ''),
            'impact': int(fields.get('impact', '-1')),
            'sides': SIDES.get(int(fields.get('sides', '3')), 'both'),
        }
        for key in ('time', 'duration'):
            if key in fields:
                row[key] = round(float(fields[key]), 3)
        for key in ('left', 'right'):
            if key in fields:
                row[key + '_speed'] = int(fields[key])
        rows.append(row)
    unique = {}
    for row in rows:
        unique[(row['zed'], row['clip'], row['impact'])] = row
    return sorted(unique.values(), key=lambda r: (r['zed'], r['tag'], r['clip'], r['impact']))


def markdown(rows):
    out = ['# Zed attack sides', '',
           'Which arm strikes at each melee impact (`KFAnimNotify_MeleeImpact`) of each stock attack clip, '
           'measured in game by `VRAttackSampler` (hand speed relative to the chest over +-0.05 s at the impact; '
           'both when the slower hand is at least 60% of the faster). Used by experimental arm loss (#210). '
           'Generated by `tools/replay/attack_sides.py`; data in `zed-attack-sides.json`.', '',
           '| Zed | Attack | Clip | Impact | Time s | Left UU/s | Right UU/s | Arm |',
           '| --- | --- | --- | --- | --- | --- | --- | --- |']
    for r in rows:
        out.append('| {zed} | {tag} | {clip} | {impact} | {time} | {left} | {right} | {sides} |'.format(
            zed=r['zed'], tag=r['tag'], clip=r['clip'], impact=r['impact'] if r['impact'] >= 0 else 'none',
            time=r.get('time', ''), left=r.get('left_speed', ''), right=r.get('right_speed', ''), sides=r['sides']))
    return '\n'.join(out) + '\n'


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('logs', nargs='+')
    ap.add_argument('--json')
    ap.add_argument('--md')
    args = ap.parse_args(argv)
    lines = []
    for path in args.logs:
        lines += Path(path).read_text(encoding='utf-8', errors='replace').splitlines()
    rows = parse(lines)
    if args.json:
        Path(args.json).write_text(json.dumps(rows, indent=1) + '\n', encoding='utf-8')
    if args.md:
        Path(args.md).write_text(markdown(rows), encoding='utf-8')
    if not args.json and not args.md:
        sys.stdout.write(markdown(rows))
    return 0 if rows else 1


if __name__ == '__main__':
    sys.exit(main())

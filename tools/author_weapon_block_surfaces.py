"""Compile exact fixed-root PSK analysis JSON into native contact surfaces.

Input is the offline firearm-catalog directory produced from original stock
assets. Optional augmented surfaces include animation-audited rigid children
and explicitly bounded cosmetic flex. All faces retain original mesh topology;
there is no convexification, invented closing face or contact-margin inflation.
"""
import argparse
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("catalog", type=Path)
    parser.add_argument("blade", type=Path)
    parser.add_argument("root", type=Path)
    parser.add_argument("--augmented", type=Path)
    parser.add_argument("--world", type=Path, help="Exact visible static pickup surfaces and per-face regions")
    parser.add_argument("--rigs", type=Path, help="World gun contact surfaces in the first-person rig frame (author_world_gun_rigs.py)")
    args = parser.parse_args()
    fallbacks = json.loads((args.catalog / "fixed-surface-fallbacks.json").read_text())
    profiles = [json.loads((args.catalog / (p["metadata"]["weapon"] + ".json")).read_text())
                for p in fallbacks["profiles"]]
    if args.augmented:
        for meta in json.loads((args.augmented / "summary.json").read_text()):
            data = json.loads((args.augmented / (meta["weapon"] + ".json")).read_text())
            match = next((i for i,p in enumerate(profiles) if p["metadata"]["mesh"].upper()==meta["mesh"].upper()),None)
            if match is None: profiles.append(data)
            else: profiles[match]=data
    held_count = len(profiles)
    if args.world:
        for meta in json.loads((args.world / "summary.json").read_text()):
            data = json.loads((args.world / (meta["weapon"] + ".json")).read_text())
            if not data["metadata"].get("world_mesh"):
                raise ValueError(f"Missing exact world mesh identity: {meta['weapon']}")
            profiles.append(data)
    world_count = len(profiles)
    if args.rigs:
        for meta in json.loads((args.rigs / "summary.json").read_text()):
            data = json.loads((args.rigs / (meta["weapon"] + ".json")).read_text())
            if not data["metadata"].get("rig_weapon"):
                raise ValueError(f"Missing world gun rig identity: {meta['weapon']}")
            profiles.append(data)
    native = ["// Generated by tools/author_weapon_block_surfaces.py from exact stock fixed-root surfaces.",
              "namespace kf2vr::adapter::weaponblock::catalog {"]
    script = ["// Exact first-person mesh identities for the native fixed-root surface catalog.",
              "class VRWeaponBlockSurfaceIds extends Object;", "static function int Get(KFWeapon W)",
              "{", "    local string Mesh;", "    if(W==None) return 0;", "    Mesh=Caps(W.FirstPersonMeshName);"]
    world_script = ["static function int GetWorld(StaticMesh Model)", "{", "    local string Mesh;",
                    "    if(Model==None) return 0;", "    Mesh=Caps(PathName(Model));"]
    rig_script = ["// One-frame world guns: contact surfaces in the rig frame (VRWorldGunRigs).",
                  "static function int GetRig(name Weapon)", "{"]
    def vec(v):
        return "{" + ",".join(f"{float(x):.6f}f" for x in v) + "}"
    def tri(v):
        return "{" + ",".join(vec(x) for x in v) + "}"
    sharp_refs = []
    for index, data in enumerate(profiles, 1):
        meta = data["metadata"]
        native += [f"// {meta['mesh']} | original PSK SHA256 {meta['sha256']}"]
        if "animation_sha256" in meta:
            native += [f"// Animation PSA SHA256 {meta['animation_sha256']}",
                       f"// {meta['pose']}; bones: {', '.join(meta['included_bones'])}",
                       f"// {meta['approximation']}; maximum sampled child deviation {meta['maximum_sampled_child_surface_deviation_uu']:.6f} UU."]
        native += [f"constexpr Vec vertices{index}[] = {{"]
        native += ["    " + vec(vertex) + "," for vertex in data["vertices"]]
        native += ["};", f"constexpr std::array<unsigned,3> triangles{index}[] = {{"]
        native += ["    {" + ",".join(str(int(i)) for i in face) + "}," for face in data["triangles"]]
        native += ["};"]
        count = len(data["triangles"])
        material = data.get("face_materials", [-1] * count)
        source = data.get("original_faces", [-1] * count)
        region = data.get("face_regions", [0] * count)
        if len(material) != count or len(source) != count or len(region) != count:
            raise ValueError(f"Face provenance length mismatch: {meta['weapon']}")
        if any(x not in (0, 1, 2) for x in region):
            raise ValueError(f"Unknown contact region: {meta['weapon']}")
        native += [f"constexpr FaceInfo info{index}[] = {{",
                   ",".join("{" + f"{int(s)},{int(m)},{int(r)}" + "}" for s,m,r in zip(source,material,region)), "};"]
        sharp = meta.get("sharp_regions")
        if sharp:
            sections = sharp.get("edge_sections", [])
            sides = int(sharp.get("edge_sides", 0))
            edges = []
            if sections and sides not in (1, 2, 3):
                raise ValueError(f"Cutting side must be authored explicitly: {meta['weapon']}")
            for a,b in zip(sections,sections[1:]):
                if b[0] < a[0]:
                    raise ValueError(f"Edge sections must follow increasing Z: {meta['weapon']}")
                for side in (1,2):
                    if sides & side:
                        edges.append(([a[side],0,a[0]],[b[side],0,b[0]],[-1 if side==1 else 1,0,0]))
            for line in sharp.get("edge_polylines", []):
                points=line["points"] if isinstance(line,dict) else line
                axes=line.get("axes",[]) if isinstance(line,dict) else []
                if axes and len(axes)!=len(points)-1:
                    raise ValueError(f"Cutting axis count mismatch: {meta['weapon']}")
                edges.extend((a,b,axes[i] if axes else sharp.get("edge_axis",[0,0,0]))
                             for i,(a,b) in enumerate(zip(points,points[1:])))
            if edges:
                native += [f"constexpr SharpEdge edges{index}[] = {{",
                           ",".join("{"+vec(a)+","+vec(b)+","+vec(axis)+"}" for a,b,axis in edges), "};"]
            tip = vec(sharp.get("tip", [0,0,0]))
            edge_ref = f"std::span<const SharpEdge>(edges{index})" if edges else "{}"
            sharp_refs.append("{"+f"{tip},{float(sharp.get('tip_radius',0)):.6f}f,"
                              +f"{float(sharp.get('edge_radius',.25)):.6f}f,{float(sharp.get('edge_min_z',-10000)):.6f}f,"
                              +("true" if sections else "false")+","+edge_ref+","
                              +vec(sharp.get("tip_axis",[0,0,0]))+","+vec(sharp.get("edge_axis",[0,0,0]))+"}")
        else:
            sharp_refs.append("{}")
        if index <= held_count:
            script += [f'    if(Mesh=="{meta["mesh"].upper()}") return {index};']
        elif index <= world_count:
            world_script += [f'    if(Mesh=="{meta["world_mesh"].upper()}") return {index};']
        else:
            rig_script += [f"    if(Weapon=='{meta['rig_weapon']}') return {index};"]
    native += [f"constexpr std::array<IndexedMesh,{len(profiles)}> meshes = {{",
               ",".join(f"IndexedMesh{{vertices{i},triangles{i}}}" for i in range(1,len(profiles)+1)), "};"]
    native += [f"constexpr std::array<std::span<const FaceInfo>,{len(profiles)}> faceInfo = {{",
               ",".join(f"std::span<const FaceInfo>(info{i})" for i in range(1,len(profiles)+1)), "};",
               f"constexpr unsigned heldCount={held_count};"]
    native += [f"constexpr std::array<SharpRegions,{len(profiles)}> sharp = {{",
               ",".join("SharpRegions"+ref for ref in sharp_refs), "};"]
    blade = json.loads(args.blade.read_text())
    # The blade source is a measured, indexed original-mesh triangle selection.
    blade = blade["Gorefast"]
    vertices = dict(zip(blade["blade_point_indices"], blade["blade_vertices"]))
    native += ["constexpr Triangle blade[] = {"]
    native += ["    " + tri([vertices[i] for i in face]) + "," for face in blade["blade_triangles"]]
    native += ["};", "}"]
    script += ["    return 0;", "}"]
    world_script += ["    return 0;", "}"]
    script += world_script
    if args.rigs:
        script += rig_script + ["    return 0;", "}"]
    (args.root / "native/adapter/WeaponBlockSurfaceCatalog.h").write_text("\n".join(native)+"\n")
    (args.root / "script/KF2VR/Classes/VRWeaponBlockSurfaceIds.uc").write_text("\n".join(script)+"\n")


if __name__ == "__main__":
    main()
